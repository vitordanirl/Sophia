CREATE TABLE IF NOT EXISTS "__EFMigrationsHistory" (
    migration_id character varying(150) NOT NULL,
    product_version character varying(32) NOT NULL,
    CONSTRAINT pk___ef_migrations_history PRIMARY KEY (migration_id)
);

START TRANSACTION;

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE clientes (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    cpf character(11) NOT NULL,
    nome character varying(150) NOT NULL,
    data_nascimento date,
    email character varying(254),
    telefone character varying(11),
    CONSTRAINT pk_clientes PRIMARY KEY (id)
);

CREATE TABLE produtos (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    nome citext NOT NULL,
    valor_unitario numeric(18,2) NOT NULL,
    CONSTRAINT pk_produtos PRIMARY KEY (id),
    CONSTRAINT ck_produtos_nome_tamanho CHECK (char_length(nome) <= 120),
    CONSTRAINT ck_produtos_valor_unitario_positivo CHECK (valor_unitario > 0)
);

CREATE TABLE vendas (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    data_venda date NOT NULL,
    cliente_id integer NOT NULL,
    CONSTRAINT pk_vendas PRIMARY KEY (id),
    CONSTRAINT fk_vendas_clientes_cliente_id FOREIGN KEY (cliente_id) REFERENCES clientes (id) ON DELETE RESTRICT
);

CREATE TABLE itens_venda (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    venda_id integer NOT NULL,
    produto_id integer NOT NULL,
    quantidade integer NOT NULL,
    valor_unitario numeric(18,2) NOT NULL,
    CONSTRAINT pk_itens_venda PRIMARY KEY (id),
    CONSTRAINT ck_itens_venda_quantidade_positiva CHECK (quantidade > 0),
    CONSTRAINT ck_itens_venda_valor_unitario_positivo CHECK (valor_unitario > 0),
    CONSTRAINT fk_itens_venda_produtos_produto_id FOREIGN KEY (produto_id) REFERENCES produtos (id) ON DELETE RESTRICT,
    CONSTRAINT fk_itens_venda_vendas_venda_id FOREIGN KEY (venda_id) REFERENCES vendas (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX ix_clientes_cpf ON clientes (cpf);

CREATE INDEX ix_clientes_nome ON clientes (nome);

CREATE INDEX ix_itens_venda_produto_id ON itens_venda (produto_id);

CREATE UNIQUE INDEX ix_itens_venda_venda_id_produto_id ON itens_venda (venda_id, produto_id);

CREATE UNIQUE INDEX ix_produtos_nome ON produtos (nome);

CREATE INDEX ix_vendas_cliente_id ON vendas (cliente_id);

CREATE INDEX ix_vendas_data_venda ON vendas (data_venda);

INSERT INTO "__EFMigrationsHistory" (migration_id, product_version)
VALUES ('20261012221251_InitialCreate', '8.0.11');

COMMIT;

